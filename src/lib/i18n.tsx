const dicts: Record<Lang, Dict> = { en, vi, fr, es, de };

type I18nContextType = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nContextType>({
  lang: 'en',
  setLang: () => {},
  t: (key) => key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('angames_lang');
    if (saved && ['en', 'vi', 'fr', 'es', 'de'].includes(saved)) return saved as Lang;
    return 'en';
  });

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem('angames_lang', l);
  };

  const t = (key: string) => dicts[lang][key] ?? key;

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
